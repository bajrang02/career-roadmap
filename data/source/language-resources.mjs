export function languageResources(label, langSlug) {
  const lang = LANGUAGES[langSlug];
  if (!lang) return null;
  const key = norm(label);
  const topic = TOPIC_ALIASES[key] || key;
  const t = lang.topics[topic];
  if (!t) return null;
  const out = [];
  if (t.o) out.push({ t: t.o[0], u: t.o[1], k: "docs" });
  if (t.w && lang.w3) out.push({ t: `${lang.name} ${topic.replace(/_/g, " ")} — W3Schools`, u: `https://www.w3schools.com/${lang.w3dir ?? lang.w3}/${t.w}.${lang.w3ext ?? "asp"}`, k: "course" });
  for (const s of sharedFor(lang)) {
    if (!out.some((x) => x.u === s.u)) out.push(s);
  }
  return out.slice(0, 4);
}
